
function results = calculateReferenceEnergyBalances( ...
    hourlyImports_kWh, hourlyExports_kWh, calendar)
% CALCULATEREFERENCEENERGYBALANCES
% Calculate annual SCE delivery and EPIC generation
% energy balances for multiple retrofit configurations.
%
% Reference tariffs:
% SCE delivery: October 1, 2026
% EPIC generation: February 1, 2024
%
% These are energy balances, NOT final utility bills.

    sce = econ.loadSCEDeliveryReferenceTariff();
    epic = econ.loadEPICReferenceTariff();

    assert(isequal(sce.periods, epic.periods), ...
        'SCE and EPIC TOU periods do not match.');

    assert(isequal(size(hourlyImports_kWh), ...
                   size(hourlyExports_kWh)), ...
        'Import and export matrices must match.');

    nScenarios = size(hourlyImports_kWh, 2);

    assert(size(hourlyImports_kWh,1) == height(calendar), ...
        'Hourly data and calendar lengths do not match.');

    sceImport = zeros(nScenarios,1);
    sceExport = zeros(nScenarios,1);
    epicImport = zeros(nScenarios,1);
    epicExport = zeros(nScenarios,1);

    for s = 1:nScenarios

        tou = econ.aggregateSCETOU( ...
            hourlyImports_kWh(:,s), ...
            hourlyExports_kWh(:,s), ...
            calendar);

        assert(isequal(string(tou.Period), sce.periods), ...
            'Unexpected TOU period ordering.');

        sceImport(s) = sum( ...
            tou.Imports_kWh .* sce.deliveryRates);

        sceExport(s) = sum( ...
            tou.Exports_kWh .* sce.deliveryRates);

        epicImport(s) = sum( ...
            tou.Imports_kWh .* epic.generationRates);

        epicExport(s) = sum( ...
            tou.Exports_kWh .* epic.generationRates);
    end

    sceNet = sceImport - sceExport;
    epicNet = epicImport - epicExport;

    results = table( ...
        sceImport, sceExport, sceNet, ...
        epicImport, epicExport, epicNet, ...
        sceNet + epicNet, ...
        'VariableNames', { ...
        'SCE_ImportValue', ...
        'SCE_ExportValue', ...
        'SCE_NetValue', ...
        'EPIC_ImportValue', ...
        'EPIC_ExportValue', ...
        'EPIC_NetValue', ...
        'CombinedNetValue'});
end
