
%% SYS 800 - Final Large Household Selection
% Representative household: 2500-2999 sq ft
% Selection: closest to median annual electricity consumption

clear; clc;

%% 1. Load required metadata columns

ds = parquetDatastore("data/metadata.parquet");

ds.SelectedVariableNames = { ...
    'bldg_id', ...
    'in_county', ...
    'in_weather_file_city', ...
    'in_geometry_building_type_recs', ...
    'in_geometry_floor_area', ...
    'in_occupants', ...
    'in_heating_fuel', ...
    'in_hvac_cooling_type', ...
    'in_water_heater_fuel', ...
    'out_electricity_total_energy_consumption'};

metadata = readall(ds);

%% 2. Apply identical household characteristics

mask = ...
    string(metadata.in_county) == "G0600370" & ...
    string(metadata.in_weather_file_city) == "Lancaster Fox Field" & ...
    string(metadata.in_geometry_building_type_recs) == ...
        "Single-Family Detached" & ...
    string(metadata.in_geometry_floor_area) == "2500-2999" & ...
    string(metadata.in_occupants) == "3" & ...
    string(metadata.in_heating_fuel) == "Natural Gas" & ...
    string(metadata.in_hvac_cooling_type) == "Central AC" & ...
    string(metadata.in_water_heater_fuel) == "Natural Gas";

candidates = metadata(mask,:);

%% 3. Remove invalid annual demand values

demand = double( ...
    candidates.out_electricity_total_energy_consumption);

valid = isfinite(demand) & demand > 0;

candidates = candidates(valid,:);
demand = demand(valid);

assert(~isempty(demand), ...
    'No qualifying large households were found.');

%% 4. Select household closest to median

medianDemand = median(demand);

[~,idx] = min(abs(demand - medianDemand));

selected = candidates(idx,:);

%% 5. Display results

fprintf('\n=== FINAL LARGE HOUSEHOLD SELECTION ===\n');

fprintf('Floor area: 2500-2999 sq ft\n');

fprintf('Qualifying households: %d\n', ...
    height(candidates));

fprintf('Median annual demand: %.2f kWh\n', ...
    medianDemand);

fprintf('Selected building ID: %s\n', ...
    string(selected.bldg_id));

fprintf('Selected annual demand: %.2f kWh\n', ...
    demand(idx));

fprintf('Difference from median: %.2f kWh\n', ...
    demand(idx) - medianDemand);

fprintf('\n=== SELECTION COMPLETE ===\n');
