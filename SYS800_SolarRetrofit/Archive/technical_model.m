
%% SYS 800 - Residential Solar Retrofit Decision Model (v4)
% Technical performance model:
% Existing aged PV + new PV + battery storage.
%
% Homeowner-adjustable inputs:
%   1. Home square footage
%   2. Existing PV capacity (kW)
%   3. Existing PV installation year
%   4. Original NEM interconnection year (optional override)
%
% Run from project root containing data/, +sim/, and +econ/.
%
% Results:
%   retrofitComparison
%   economicComparison
%   technicalPerformance
%   monthlyResults
%
% The PVWatts reference profile represents a NEW 6 kW PV system.
% Existing PV capacity is a homeowner input, NOT a fixed 6 kW value.

%% 1. Configuration

location.city = "Palmdale";
location.state = "California";
location.latitude = 34.58;
location.longitude = -118.12;

%% 1.1 Homeowner inputs

% Homeowner inputs are collected by main.m; no competing defaults here.
assert(exist('homeownerInputs','var') == 1 && isstruct(homeownerInputs), ...
    'Run main.m to enter homeowner inputs before the technical model.');

requiredInputFields = { ...
    'homeArea_sqft', ...
    'existingPV_kW', ...
    'pvInstallationYear'};

for k = 1:numel(requiredInputFields)
    assert(isfield(homeownerInputs,requiredInputFields{k}), ...
        "Missing homeowner input: " + requiredInputFields{k});
end

house.targetArea_sqft = homeownerInputs.homeArea_sqft;
pv.capacity_kW = homeownerInputs.existingPV_kW;
% Model age is derived rather than entered independently.
% For a 2027 evaluation, a 2017 installation corresponds to 10 years.
analysisStartYear = 2027;
assert(isnumeric(homeownerInputs.pvInstallationYear) && ...
    isscalar(homeownerInputs.pvInstallationYear) && ...
    isfinite(homeownerInputs.pvInstallationYear) && ...
    homeownerInputs.pvInstallationYear == floor(homeownerInputs.pvInstallationYear) && ...
    homeownerInputs.pvInstallationYear >= 1900 && ...
    homeownerInputs.pvInstallationYear <= analysisStartYear, ...
    'PV installation year must be an integer between 1900 and 2027.');
pv.installationYear = homeownerInputs.pvInstallationYear;
pv.age_years = analysisStartYear - pv.installationYear;

% NEM interconnection defaults to the original PV installation year.
% Set an override for replacements or other documented exceptions.
if ~isfield(homeownerInputs,'originalInterconnectionYear') || ...
        isempty(homeownerInputs.originalInterconnectionYear)
    homeownerInputs.originalInterconnectionYear = pv.installationYear;
end
assert(isnumeric(homeownerInputs.originalInterconnectionYear) && ...
    isscalar(homeownerInputs.originalInterconnectionYear) && ...
    isfinite(homeownerInputs.originalInterconnectionYear) && ...
    homeownerInputs.originalInterconnectionYear == floor(homeownerInputs.originalInterconnectionYear) && ...
    homeownerInputs.originalInterconnectionYear >= 1900 && ...
    homeownerInputs.originalInterconnectionYear <= analysisStartYear, ...
    'Original NEM interconnection year must be an integer between 1900 and 2027.');

assert(isnumeric(house.targetArea_sqft) && ...
    isscalar(house.targetArea_sqft) && ...
    isfinite(house.targetArea_sqft) && ...
    house.targetArea_sqft > 0, ...
    "Home square footage must be a positive number.");

assert(isnumeric(pv.capacity_kW) && ...
    isscalar(pv.capacity_kW) && ...
    isfinite(pv.capacity_kW) && ...
    pv.capacity_kW > 0, ...
    "Existing PV capacity must be positive.");

assert(isnumeric(pv.age_years) && ...
    isscalar(pv.age_years) && ...
    isfinite(pv.age_years) && ...
    pv.age_years >= 0, ...
    "Existing PV age must be nonnegative.");

%% 1.2 Representative ResStock household selection

% Three representative household profiles selected from:
% ResStock 2021.1 End Use Load Profiles, AMY 2018.
%
% Common characteristics:
% Los Angeles County
% Lancaster Fox Field weather station
% Single-family detached
% Three occupants
% Natural-gas heating and water heating
% Central air conditioning
%
% Home size selects an actual representative hourly load profile.
% Electricity demand is NOT scaled linearly with square footage.

if house.targetArea_sqft >= 1000 && ...
        house.targetArea_sqft <= 1499

    house.sizeCategory = "Small";
    house.resstockBuildingID = 337387;
    house.referenceAreaRange = "1000-1499";

elseif house.targetArea_sqft >= 1500 && ...
        house.targetArea_sqft <= 1999

    house.sizeCategory = "Medium";
    house.resstockBuildingID = 198638;
    house.referenceAreaRange = "1500-1999";

elseif house.targetArea_sqft >= 2500 && ...
        house.targetArea_sqft <= 2999

    house.sizeCategory = "Large";
    house.resstockBuildingID = 4778;
    house.referenceAreaRange = "2500-2999";

else
    error(['Home square footage is outside the three modeled ' ...
        'ResStock categories: 1000-1499, 1500-1999, ' ...
        'and 2500-2999 sq ft.']);
end

house.occupants = 3;
house.type = "Single Family Detached";
house.heating = "Natural Gas";
house.cooling = "Central AC";
house.waterHeating = "Natural Gas";

% Exact square footage is not known for all reference buildings.
% The original medium building was previously identified as 1690 sq ft.
house.referenceArea_sqft = NaN;

if house.resstockBuildingID == 198638
    house.referenceArea_sqft = 1690;
end

%% 1.3 PV configuration

% FIXED reference capacity used to generate the PVWatts CSV.
% This is not the homeowner's installed capacity.
pv.referenceCapacity_kW = 6;

% Existing PV degradation assumption.
pv.degradationRate = 0.005;

% Retrofit scenarios: additional NEW PV capacity.
pv.addedCapacityScenarios_kW = [0 2 4];

%% 1.4 Battery configuration

battery.capacityScenarios_kWh = [0 5 10 15 20];
battery.capacity_kWh = 10;
battery.maxChargePower_kW = 5;
battery.maxDischargePower_kW = 5;
battery.roundTripEfficiency = 0.90;
battery.initialSOC_kWh = 0;

%% 1.5 Simulation settings

settings.hoursPerYear = 8760;
settings.timeStep_hours = 1;
settings.showFigures = true;

%% 1.6 Display selected homeowner configuration

fprintf('\n=== HOMEOWNER CONFIGURATION ===\n');
fprintf('Location: %s, %s\n', ...
    location.city,location.state);
fprintf('Home square footage: %.0f sq ft\n', ...
    house.targetArea_sqft);
fprintf('Household category: %s\n', ...
    house.sizeCategory);
fprintf('ResStock floor-area range: %s sq ft\n', ...
    house.referenceAreaRange);
fprintf('ResStock building ID: %d\n', ...
    house.resstockBuildingID);
fprintf('Existing PV capacity: %.2f kW\n', ...
    pv.capacity_kW);
fprintf('PV installation year: %d\n', pv.installationYear);
fprintf('Original NEM interconnection year: %d\n', ...
    homeownerInputs.originalInterconnectionYear);
fprintf('Existing PV age: %.1f years\n', ...
    pv.age_years);
fprintf('PVWatts reference capacity: %.2f kW\n', ...
    pv.referenceCapacity_kW);

%% 2. Load and prepare hourly input data

pvFile = fullfile("data","pvwatts_hourly.csv");

loadFile = fullfile("data", ...
    sprintf("%d-0.parquet",house.resstockBuildingID));

assert(isfile(pvFile), ...
    "PVWatts CSV not found. Run from project root.");

assert(isfile(loadFile), ...
    "ResStock hourly file not found: " + loadFile);

%% 2.1 Load PVWatts reference generation

pvData = readtable(pvFile, ...
    "NumHeaderLines",31, ...
    "VariableNamingRule","preserve");

assert(height(pvData) == settings.hoursPerYear, ...
    "PVWatts must contain 8760 hourly records.");

% PVWatts CSV represents an undegraded 6 kW PV system.
% Convert hourly AC power (W) into hourly energy (kWh).

solarReference_kWh = ...
    pvData.("AC System Output (W)") / 1000 * ...
    settings.timeStep_hours;

solarReference_kWh = solarReference_kWh(:);

solarIrradiance = ...
    pvData.("Plane of Array Irradiance (W/m2)");

solarIrradiance = solarIrradiance(:);

assert(all(isfinite(solarReference_kWh)) && ...
    all(solarReference_kWh >= 0), ...
    "PVWatts generation must be finite and nonnegative.");

%% 2.2 Scale reference generation to homeowner PV capacity

% Existing PV capacity is variable.
% Reference PVWatts capacity remains fixed at 6 kW.

solarEnergy_kWh = solarReference_kWh * ...
    (pv.capacity_kW / pv.referenceCapacity_kW);

% Apply accumulated degradation to EXISTING PV only.

degradationFactor = ...
    (1-pv.degradationRate)^pv.age_years;

solarAged_kWh = solarEnergy_kWh * degradationFactor;

%% 2.3 Load selected ResStock demand profile

loadData = parquetread(loadFile);

assert(height(loadData) == 35040, ...
    "ResStock must contain 35040 15-minute records.");

demand15min_kWh = ...
    loadData.out_electricity_total_energy_consumption;

demand15min_kWh = demand15min_kWh(:);

assert(all(isfinite(demand15min_kWh)) && ...
    all(demand15min_kWh >= 0), ...
    "ResStock demand must be finite and nonnegative.");

% ResStock values are kWh PER 15-minute interval.
% Sum groups of four; do not multiply by 0.25.

demandHourly_kWh = ...
    sum(reshape(demand15min_kWh,4,[]),1)';

assert(numel(demandHourly_kWh) == settings.hoursPerYear, ...
    "Demand must contain 8760 hourly records.");

assert(all(isfinite(solarAged_kWh)) && ...
    all(solarAged_kWh >= 0), ...
    "PV generation must be finite and nonnegative.");

annualDemand_kWh = sum(demandHourly_kWh);
annualSolarAged_kWh = sum(solarAged_kWh);

fprintf('\n=== ANNUAL INPUT SUMMARY ===\n');
fprintf('Annual household demand: %.2f kWh\n', ...
    annualDemand_kWh);
fprintf('Annual existing PV generation: %.2f kWh\n', ...
    annualSolarAged_kWh);
fprintf('Existing PV retention factor: %.4f\n', ...
    degradationFactor);

%% 3. Existing system: no retrofit

baseline = sim.calculateEnergyFlows( ...
    demandHourly_kWh,solarAged_kWh);

annualGridImport_kWh = sum(baseline.gridImport_kWh);
annualGridExport_kWh = sum(baseline.gridExport_kWh);
annualSelfConsumed_kWh = sum(baseline.selfConsumed_kWh);

%% 3.1 Monthly energy aggregation

% Non-leap-year calendar.
% PVWatts and ResStock represent different weather-year sources
% and are not coincident measurements.

monthNames = ["Jan" "Feb" "Mar" "Apr" "May" "Jun" ...
              "Jul" "Aug" "Sep" "Oct" "Nov" "Dec"];

daysPerMonth = [31 28 31 30 31 30 31 31 30 31 30 31];

monthEndHours = cumsum(daysPerMonth)*24;
monthStartHours = [1 monthEndHours(1:end-1)+1];

monthlyDemand_kWh = zeros(12,1);
monthlySolar_kWh = zeros(12,1);
monthlyImport_kWh = zeros(12,1);
monthlyExport_kWh = zeros(12,1);

for m = 1:12

    idx = monthStartHours(m):monthEndHours(m);

    monthlyDemand_kWh(m) = ...
        sum(demandHourly_kWh(idx));

    monthlySolar_kWh(m) = ...
        sum(solarAged_kWh(idx));

    monthlyImport_kWh(m) = ...
        sum(baseline.gridImport_kWh(idx));

    monthlyExport_kWh(m) = ...
        sum(baseline.gridExport_kWh(idx));

end

monthlyResults = table( ...
    monthNames', ...
    monthlyDemand_kWh, ...
    monthlySolar_kWh, ...
    monthlyImport_kWh, ...
    monthlyExport_kWh, ...
    'VariableNames',{ ...
    'Month', ...
    'Demand_kWh', ...
    'Solar_kWh', ...
    'GridImport_kWh', ...
    'GridExport_kWh'});

%% 4. Retrofit trade study
% Existing aged PV + NEW PV + battery storage.

addedPVSizes = pv.addedCapacityScenarios_kW;
batterySizes = battery.capacityScenarios_kWh;

numAddedPV = numel(addedPVSizes);
numBattery = numel(batterySizes);

numRetrofitScenarios = numAddedPV*numBattery;

assert(any(addedPVSizes==0) && any(batterySizes==0), ...
    "Scenario lists must include a zero-PV and zero-battery baseline.");

assert(all(addedPVSizes>=0) && all(batterySizes>=0), ...
    "Retrofit capacities must be nonnegative.");

retrofitAddedPV_kW = zeros(numRetrofitScenarios,1);
retrofitBattery_kWh = zeros(numRetrofitScenarios,1);
retrofitGeneration_kWh = zeros(numRetrofitScenarios,1);
retrofitImports_kWh = zeros(numRetrofitScenarios,1);
retrofitExports_kWh = zeros(numRetrofitScenarios,1);
retrofitImportReduction_pct = zeros(numRetrofitScenarios,1);
retrofitDischarge_kWh = zeros(numRetrofitScenarios,1);

% Preserve hourly grid exchanges for tariff calculations.

hourlyRetrofitImports_kWh = ...
    zeros(settings.hoursPerYear,numRetrofitScenarios);

hourlyRetrofitExports_kWh = ...
    zeros(settings.hoursPerYear,numRetrofitScenarios);

%% 4.1 Verification settings

maxHourlyBalanceError = 0;
maxSOCBalanceError = 0;

eta = sqrt(battery.roundTripEfficiency);
tolerance = 1e-8;

scenarioIndex = 0;

%% 4.2 Evaluate retrofit configurations

for i = 1:numAddedPV

    % Newly installed PV uses the UNDEGRADED reference generation.
    % Its output is independent of the homeowner's existing PV capacity.

    newPV_kWh = solarReference_kWh * ...
        (addedPVSizes(i)/pv.referenceCapacity_kW);

    totalSolar_kWh = solarAged_kWh + newPV_kWh;

    for j = 1:numBattery

        scenarioIndex = scenarioIndex+1;

        testBattery = battery;
        testBattery.capacity_kWh = batterySizes(j);

        scenario = sim.calculateBatteryDispatch( ...
            demandHourly_kWh,totalSolar_kWh,testBattery);

        retrofitAddedPV_kW(scenarioIndex) = ...
            addedPVSizes(i);

        retrofitBattery_kWh(scenarioIndex) = ...
            batterySizes(j);

        retrofitGeneration_kWh(scenarioIndex) = ...
            sum(totalSolar_kWh);

        retrofitImports_kWh(scenarioIndex) = ...
            sum(scenario.gridImport_kWh);

        retrofitExports_kWh(scenarioIndex) = ...
            sum(scenario.gridExport_kWh);

        hourlyRetrofitImports_kWh(:,scenarioIndex) = ...
            scenario.gridImport_kWh(:);

        hourlyRetrofitExports_kWh(:,scenarioIndex) = ...
            scenario.gridExport_kWh(:);

        retrofitDischarge_kWh(scenarioIndex) = ...
            sum(scenario.batteryDischarge_kWh);

        retrofitImportReduction_pct(scenarioIndex) = ...
            100*(annualGridImport_kWh - ...
            retrofitImports_kWh(scenarioIndex)) / ...
            annualGridImport_kWh;

        %% Energy conservation verification

        soc = scenario.stateOfCharge_kWh;

        hourlyBalance = ...
            demandHourly_kWh + ...
            scenario.batteryCharge_kWh + ...
            scenario.gridExport_kWh - ...
            totalSolar_kWh - ...
            scenario.batteryDischarge_kWh - ...
            scenario.gridImport_kWh;

        maxHourlyBalanceError = max( ...
            maxHourlyBalanceError, ...
            max(abs(hourlyBalance)));

        socStart = [testBattery.initialSOC_kWh; ...
            soc(1:end-1)];

        socExpected = socStart + ...
            eta*scenario.batteryCharge_kWh - ...
            scenario.batteryDischarge_kWh/eta;

        maxSOCBalanceError = max( ...
            maxSOCBalanceError, ...
            max(abs(soc-socExpected)));

        assert(all(soc >= -tolerance) && ...
            all(soc <= testBattery.capacity_kWh+tolerance), ...
            "Battery SOC outside capacity limits.");

        assert(all(scenario.batteryCharge_kWh >= -tolerance) && ...
            all(scenario.batteryCharge_kWh <= ...
            testBattery.maxChargePower_kW* ...
            settings.timeStep_hours+tolerance), ...
            "Battery charging power limit violated.");

        assert(all(scenario.batteryDischarge_kWh >= -tolerance) && ...
            all(scenario.batteryDischarge_kWh <= ...
            testBattery.maxDischargePower_kW* ...
            settings.timeStep_hours+tolerance), ...
            "Battery discharging power limit violated.");

        assert(all(scenario.gridImport_kWh >= -tolerance) && ...
            all(scenario.gridExport_kWh >= -tolerance), ...
            "Negative grid exchanges detected.");

    end
end

retrofitComparison = table( ...
    retrofitAddedPV_kW, ...
    retrofitBattery_kWh, ...
    retrofitGeneration_kWh, ...
    retrofitImports_kWh, ...
    retrofitExports_kWh, ...
    retrofitImportReduction_pct, ...
    'VariableNames',{ ...
    'AddedPV_kW', ...
    'BatteryCapacity_kWh', ...
    'Generation_kWh', ...
    'GridImports_kWh', ...
    'GridExports_kWh', ...
    'ImportReduction_pct'});

%% 5. Technical model verification

assert(isequal(size(hourlyRetrofitImports_kWh), ...
    [settings.hoursPerYear,numRetrofitScenarios]));

assert(isequal(size(hourlyRetrofitExports_kWh), ...
    [settings.hoursPerYear,numRetrofitScenarios]));

assert(all(abs(sum(hourlyRetrofitImports_kWh,1)' - ...
    retrofitImports_kWh)<tolerance), ...
    "Hourly import totals mismatch annual totals.");

assert(all(abs(sum(hourlyRetrofitExports_kWh,1)' - ...
    retrofitExports_kWh)<tolerance), ...
    "Hourly export totals mismatch annual totals.");

assert(maxHourlyBalanceError < tolerance, ...
    "Hourly energy conservation failed.");

assert(maxSOCBalanceError < tolerance, ...
    "Battery SOC conservation failed.");

assert(abs(sum(monthlyDemand_kWh)-annualDemand_kWh) < tolerance, ...
    "Monthly demand does not sum to annual demand.");

assert(abs(sum(monthlySolar_kWh)-annualSolarAged_kWh) < tolerance, ...
    "Monthly PV generation does not sum to annual PV generation.");

assert(abs(sum(monthlyImport_kWh)-annualGridImport_kWh) < tolerance, ...
    "Monthly grid imports do not sum to annual imports.");

assert(abs(sum(monthlyExport_kWh)-annualGridExport_kWh) < tolerance, ...
    "Monthly grid exports do not sum to annual exports.");

%% 5.1 Verify no-retrofit baseline

baseIdx = ...
    retrofitAddedPV_kW==0 & ...
    retrofitBattery_kWh==0;

assert(nnz(baseIdx)==1, ...
    "Expected exactly one baseline configuration.");

assert(all(abs( ...
    hourlyRetrofitImports_kWh(:,baseIdx) - ...
    baseline.gridImport_kWh(:))<tolerance));

assert(all(abs( ...
    hourlyRetrofitExports_kWh(:,baseIdx) - ...
    baseline.gridExport_kWh(:))<tolerance));

assert(abs( ...
    retrofitImports_kWh(baseIdx) - ...
    annualGridImport_kWh)<tolerance, ...
    "Retrofit baseline imports mismatch.");

assert(abs( ...
    retrofitExports_kWh(baseIdx) - ...
    annualGridExport_kWh)<tolerance, ...
    "Retrofit baseline exports mismatch.");

assert(abs( ...
    retrofitGeneration_kWh(baseIdx) - ...
    annualSolarAged_kWh)<tolerance, ...
    "Retrofit baseline PV generation mismatch.");

%% 5.2 Independent PV-only verification

for i = 1:numAddedPV

    idx = ...
        retrofitAddedPV_kW==addedPVSizes(i) & ...
        retrofitBattery_kWh==0;

    testSolar = solarAged_kWh + ...
        solarReference_kWh * ...
        (addedPVSizes(i)/pv.referenceCapacity_kW);

    testFlows = sim.calculateEnergyFlows( ...
        demandHourly_kWh,testSolar);

    assert(nnz(idx)==1 && ...
        abs(retrofitImports_kWh(idx) - ...
        sum(testFlows.gridImport_kWh))<tolerance && ...
        abs(retrofitExports_kWh(idx) - ...
        sum(testFlows.gridExport_kWh))<tolerance, ...
        "PV-only augmentation mismatch.");

end

%% 5.3 Verify scenario trends

% At fixed PV capacity, additional battery storage
% must not increase annual grid imports.

for i = 1:numAddedPV

    idx = retrofitAddedPV_kW==addedPVSizes(i);

    assert(all(diff(retrofitImports_kWh(idx))<=tolerance), ...
        "Grid imports increased with battery capacity.");

end

% At fixed battery capacity, additional PV
% must not increase annual grid imports.

for j = 1:numBattery

    idx = retrofitBattery_kWh==batterySizes(j);

    assert(all(diff(retrofitImports_kWh(idx))<=tolerance), ...
        "Grid imports increased with new PV capacity.");

end

fprintf('\n=== MODEL VERIFICATION ===\n');

fprintf('PVWatts: %d hourly records; ',height(pvData));
fprintf('ResStock: %d 15-min records. PASS\n',height(loadData));

fprintf(['Baseline: %.1f kWh demand, %.1f kWh aged PV, ' ...
    '%.1f kWh imports, %.1f kWh exports.\n'], ...
    annualDemand_kWh,annualSolarAged_kWh, ...
    annualGridImport_kWh,annualGridExport_kWh);

fprintf('Monthly aggregation and baseline scenario: PASS\n');
fprintf('PV-only cross-checks and scenario trends: PASS\n');

fprintf(['All %d battery scenarios: SOC, power limits, ' ...
    'nonnegative flows: PASS\n'],numRetrofitScenarios);

fprintf('Maximum hourly energy balance residual: %.12f kWh\n', ...
    maxHourlyBalanceError);

fprintf('Maximum hourly SOC balance residual: %.12f kWh\n', ...
    maxSOCBalanceError);

fprintf('All verification checks passed.\n');

%% 6. Economic assumptions and hourly tariff alignment

% RESEARCH ESTIMATES ONLY:
% Rounded retail tariffs and simplified annual billing.
%
% NEM1 and NEM2 NBC rates are intentionally set to zero
% for sensitivity analysis.
%
% NBT credit accounting uses a preliminary
% annual-offset approximation.
%
% PVWatts and ResStock profiles are not independently
% time-zone validated.

sceTariff = econ.loadSCETariffs();
billingAssumptions = econ.loadSCEBillingAssumptions();

economicYear = 2026;

%% 6.1 NEM import rates

[nemImportRates,economicCalendar] = ...
    econ.buildTOURates( ...
    economicYear,"TOU-D-4-9PM",sceTariff.rateTable);

%% 6.2 NBT import rates

[nbtImportRates,nbtCalendar] = ...
    econ.buildTOURates( ...
    economicYear,"TOU-D-PRIME",sceTariff.rateTable);

%% 6.3 NBT export rates

[nbtExportRates,nbtComponents] = ...
    econ.loadNBTExportRates( ...
    "data/NBT26_2026_hourly_components.csv",economicYear);

%% 6.4 Verify tariff vectors

assert(numel(nemImportRates)==settings.hoursPerYear && ...
    numel(nbtImportRates)==settings.hoursPerYear && ...
    numel(nbtExportRates)==settings.hoursPerYear, ...
    "All tariff vectors must contain 8760 hours.");

assert(isequal( ...
    economicCalendar.Timestamp,nbtCalendar.Timestamp) && ...
    isequal( ...
    economicCalendar.Timestamp,nbtComponents.Timestamp), ...
    "Economic and NBT timestamps are not aligned.");

assert(all(isfinite(nemImportRates) & nemImportRates>=0) && ...
    all(isfinite(nbtImportRates) & nbtImportRates>=0) && ...
    all(isfinite(nbtExportRates) & nbtExportRates>=0), ...
    "Tariff vectors must be finite and nonnegative.");

%% 6.5 Billing assumptions

nem1NBC_perkWh = 0;
nem2NBC_perkWh = 0;
nbtNBC_perkWh = 0;

nscRate_perkWh = billingAssumptions.nscRate_perkWh;
fixedAnnualCharge = billingAssumptions.fixedAnnualCharge;

%% 7. Annual operating costs for all retrofit scenarios

nem1AnnualCost = zeros(numRetrofitScenarios,1);
nem2AnnualCost = zeros(numRetrofitScenarios,1);
nbtAnnualCost = zeros(numRetrofitScenarios,1);

for s = 1:numRetrofitScenarios

    imports = hourlyRetrofitImports_kWh(:,s);
    exports = hourlyRetrofitExports_kWh(:,s);

    nem1 = econ.calculateNEMBill( ...
        imports,exports, ...
        nemImportRates,economicCalendar,1, ...
        nbcRate_perkWh=nem1NBC_perkWh, ...
        nscRate_perkWh=nscRate_perkWh, ...
        fixedAnnualCharge=fixedAnnualCharge);

    nem2 = econ.calculateNEMBill( ...
        imports,exports, ...
        nemImportRates,economicCalendar,2, ...
        nbcRate_perkWh=nem2NBC_perkWh, ...
        nscRate_perkWh=nscRate_perkWh, ...
        fixedAnnualCharge=fixedAnnualCharge);

    nbt = econ.calculateNBTBill( ...
        imports,exports, ...
        nbtImportRates,nbtExportRates,nbtCalendar, ...
        nbcRate_perkWh=nbtNBC_perkWh, ...
        fixedAnnualCharge=fixedAnnualCharge);

    nem1AnnualCost(s) = nem1.annualCost;
    nem2AnnualCost(s) = nem2.annualCost;
    nbtAnnualCost(s) = nbt.annualCost;

end

%% 7.1 Annual savings relative to no retrofit

baseIdx = ...
    retrofitAddedPV_kW==0 & ...
    retrofitBattery_kWh==0;

baselineScenario = find(baseIdx);

nem1AnnualSavings = ...
    nem1AnnualCost(baselineScenario)-nem1AnnualCost;

nem2AnnualSavings = ...
    nem2AnnualCost(baselineScenario)-nem2AnnualCost;

nbtAnnualSavings = ...
    nbtAnnualCost(baselineScenario)-nbtAnnualCost;

economicComparison = table( ...
    retrofitAddedPV_kW, ...
    retrofitBattery_kWh, ...
    nem1AnnualCost, ...
    nem2AnnualCost, ...
    nbtAnnualCost, ...
    nem1AnnualSavings, ...
    nem2AnnualSavings, ...
